CREATE TABLE computed_bootstrap_result (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id              TEXT NOT NULL REFERENCES evaluation_run(run_id),
    comparison_key      TEXT NOT NULL,
    metric              TEXT NOT NULL,             -- psnr|ssim
    variant_a           TEXT NOT NULL,
    variant_b           TEXT NOT NULL,
    paired_n            INTEGER NOT NULL,
    mean_delta          DOUBLE PRECISION NOT NULL,
    ci_lower            DOUBLE PRECISION NOT NULL,
    ci_upper            DOUBLE PRECISION NOT NULL,
    ci_width            DOUBLE PRECISION NOT NULL,
    significance_status TEXT NOT NULL,             -- significant|directional
    resamples           INTEGER NOT NULL,
    planned_comparisons INTEGER NOT NULL,
    corrected_alpha     DOUBLE PRECISION NOT NULL,
    seed                BIGINT NOT NULL,
    computed_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    result_version      INTEGER NOT NULL,
    UNIQUE (run_id, comparison_key, metric, result_version)
);

CREATE INDEX computed_bootstrap_result_run_idx ON computed_bootstrap_result (run_id);
CREATE INDEX computed_bootstrap_result_lookup_idx ON computed_bootstrap_result (run_id, comparison_key, metric);
