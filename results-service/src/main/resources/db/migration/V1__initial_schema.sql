-- Prelude Results Service — initial ingestion schema.
-- Policy: post-freeze changes are ADD-ONLY, team-voted, migration-scripted
-- (docs/data-contract.md §7). Enums are enforced in the application layer,
-- not via CHECK constraints, so value sets can grow add-only.

CREATE TABLE evaluation_run (
    run_id              TEXT PRIMARY KEY,
    description         TEXT,
    phase               TEXT,
    planned_test_n      INTEGER NOT NULL,
    planned_comparisons INTEGER NOT NULL,
    bootstrap_resamples INTEGER NOT NULL DEFAULT 10000,
    ci_level            DOUBLE PRECISION NOT NULL DEFAULT 0.95,
    created_by          TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE submission (
    submission_id UUID PRIMARY KEY,           -- client-generated idempotency key
    run_id        TEXT NOT NULL REFERENCES evaluation_run(run_id),
    stage         TEXT NOT NULL,
    device_id     TEXT,
    app_version   TEXT,
    occurred_at   TIMESTAMPTZ,
    received_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    payload_hash  VARCHAR(64) NOT NULL,
    payload_json  TEXT NOT NULL,              -- canonical JSON, audit trail
    image_count   INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX submission_run_stage_idx ON submission (run_id, stage);
CREATE INDEX submission_received_idx  ON submission (received_at);

-- --------------------------------------------------------------- capture

CREATE TABLE capture_frame_metric (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id               TEXT NOT NULL REFERENCES evaluation_run(run_id),
    submission_id        UUID NOT NULL REFERENCES submission(submission_id),
    image_id             TEXT NOT NULL,
    result_version       INTEGER NOT NULL,
    frame_index          INTEGER NOT NULL,
    iso                  INTEGER NOT NULL,
    exposure_time_ns     BIGINT NOT NULL,
    captured_at_epoch_ms BIGINT NOT NULL,
    sharpness_score      DOUBLE PRECISION NOT NULL,
    blur_rejected        BOOLEAN NOT NULL DEFAULT FALSE,
    emergency_fallback   BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (run_id, image_id, frame_index, result_version)
);
CREATE INDEX capture_frame_metric_lookup_idx ON capture_frame_metric (run_id, image_id);

-- ------------------------------------------------------------- alignment

CREATE TABLE alignment_image_metric (
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                        TEXT NOT NULL REFERENCES evaluation_run(run_id),
    submission_id                 UUID NOT NULL REFERENCES submission(submission_id),
    image_id                      TEXT NOT NULL,
    result_version                INTEGER NOT NULL,
    total_frame_count             INTEGER NOT NULL,
    aligned_frame_count           INTEGER NOT NULL,
    alignment_success             BOOLEAN NOT NULL,
    alignment_confidence          DOUBLE PRECISION,
    classifier_predicted_label    TEXT,
    classifier_ground_truth_label TEXT,
    classifier_correct            BOOLEAN,
    UNIQUE (run_id, image_id, result_version)
);
CREATE INDEX alignment_image_metric_lookup_idx ON alignment_image_metric (run_id, image_id);

CREATE TABLE alignment_frame_metric (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id            TEXT NOT NULL REFERENCES evaluation_run(run_id),
    submission_id     UUID NOT NULL REFERENCES submission(submission_id),
    image_id          TEXT NOT NULL,
    result_version    INTEGER NOT NULL,
    frame_index       INTEGER NOT NULL,
    ransac_inlier_ratio DOUBLE PRECISION NOT NULL,
    frame_aligned     BOOLEAN NOT NULL,
    UNIQUE (run_id, image_id, frame_index, result_version)
);
CREATE INDEX alignment_frame_metric_lookup_idx ON alignment_frame_metric (run_id, image_id);

-- Run-level classifier aggregates (per-image labels above are authoritative;
-- intentionally no uniqueness constraint: latest submission by received_at wins).
CREATE TABLE alignment_classifier_summary (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         TEXT NOT NULL REFERENCES evaluation_run(run_id),
    submission_id  UUID NOT NULL REFERENCES submission(submission_id),
    result_version INTEGER NOT NULL,
    accuracy       DOUBLE PRECISION,
    precision      DOUBLE PRECISION,
    recall         DOUBLE PRECISION,
    n_images       INTEGER NOT NULL
);
CREATE INDEX alignment_classifier_summary_run_idx ON alignment_classifier_summary (run_id);

-- ---------------------------------------------------------------- fusion

CREATE TABLE fusion_strategy_score (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         TEXT NOT NULL REFERENCES evaluation_run(run_id),
    submission_id  UUID NOT NULL REFERENCES submission(submission_id),
    image_id       TEXT NOT NULL,
    result_version INTEGER NOT NULL,
    strategy       TEXT NOT NULL,             -- naive|trimmed|confidence_weighted|learned (app-enforced)
    ssim           DOUBLE PRECISION NOT NULL,
    psnr           DOUBLE PRECISION,
    UNIQUE (run_id, image_id, strategy, result_version)
);
CREATE INDEX fusion_strategy_score_lookup_idx ON fusion_strategy_score (run_id, image_id);

-- Learned-model overfit diagnostic: inherently model-level (train vs val SSIM).
CREATE TABLE fusion_model_diagnostic (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id               TEXT NOT NULL REFERENCES evaluation_run(run_id),
    submission_id        UUID NOT NULL REFERENCES submission(submission_id),
    result_version       INTEGER NOT NULL,
    model_version        TEXT NOT NULL,
    train_ssim           DOUBLE PRECISION NOT NULL,
    val_ssim             DOUBLE PRECISION NOT NULL,
    train_val_ssim_delta DOUBLE PRECISION NOT NULL
);
CREATE INDEX fusion_model_diagnostic_run_idx ON fusion_model_diagnostic (run_id);

-- ---------------------------------------------------------------- denoise

CREATE TABLE denoise_image_metric (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                TEXT NOT NULL REFERENCES evaluation_run(run_id),
    submission_id         UUID NOT NULL REFERENCES submission(submission_id),
    image_id              TEXT NOT NULL,
    result_version        INTEGER NOT NULL,
    model_variant         TEXT NOT NULL,
    precision             TEXT NOT NULL,      -- fp32|int8 (app-enforced)
    psnr                  DOUBLE PRECISION NOT NULL,
    ssim                  DOUBLE PRECISION NOT NULL,
    latency_ms            DOUBLE PRECISION NOT NULL,
    discard_race_event    BOOLEAN NOT NULL DEFAULT FALSE,
    timeout_event         BOOLEAN NOT NULL DEFAULT FALSE,
    model_file_size_bytes BIGINT,
    UNIQUE (run_id, image_id, model_variant, precision, result_version)
);
CREATE INDEX denoise_image_metric_lookup_idx ON denoise_image_metric (run_id, image_id);

-- Restormer go/no-go anchored to Role 5a's INT8 numbers (baseline columns NOT NULL
-- by design: an unanchored comparison is a contract violation).
CREATE TABLE restormer_go_nogo (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                    TEXT NOT NULL REFERENCES evaluation_run(run_id),
    submission_id             UUID NOT NULL REFERENCES submission(submission_id),
    image_id                  TEXT NOT NULL,
    result_version            INTEGER NOT NULL,
    baseline_int8_psnr        DOUBLE PRECISION NOT NULL,
    baseline_int8_ssim        DOUBLE PRECISION NOT NULL,
    baseline_int8_latency_ms  DOUBLE PRECISION,
    restormer_psnr            DOUBLE PRECISION NOT NULL,
    restormer_ssim            DOUBLE PRECISION NOT NULL,
    restormer_latency_ms      DOUBLE PRECISION,
    UNIQUE (run_id, image_id, result_version)
);
CREATE INDEX restormer_go_nogo_lookup_idx ON restormer_go_nogo (run_id, image_id);

-- ----------------------------------------------------------- postprocess

CREATE TABLE postprocess_image_metric (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                   TEXT NOT NULL REFERENCES evaluation_run(run_id),
    submission_id            UUID NOT NULL REFERENCES submission(submission_id),
    image_id                 TEXT NOT NULL,
    result_version           INTEGER NOT NULL,
    ssim_before_postprocess  DOUBLE PRECISION,
    ssim_after_postprocess   DOUBLE PRECISION,
    ssim_contribution        DOUBLE PRECISION NOT NULL,
    full_pipeline_ssim       DOUBLE PRECISION,
    UNIQUE (run_id, image_id, result_version)
);
CREATE INDEX postprocess_image_metric_lookup_idx ON postprocess_image_metric (run_id, image_id);

-- --------------------------------------------------------------- training

CREATE TABLE training_image_score (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         TEXT NOT NULL REFERENCES evaluation_run(run_id),
    submission_id  UUID NOT NULL REFERENCES submission(submission_id),
    image_id       TEXT NOT NULL,
    result_version INTEGER NOT NULL,
    model          TEXT NOT NULL,
    epoch          INTEGER NOT NULL,
    global_step    INTEGER,
    metric_name    TEXT NOT NULL,
    value          DOUBLE PRECISION NOT NULL,
    split          TEXT NOT NULL,             -- train|validation; heldout_test rejected by the API
    UNIQUE (run_id, model, epoch, image_id, metric_name, result_version)
);
CREATE INDEX training_image_score_lookup_idx ON training_image_score (run_id, model);

CREATE TABLE training_loss_point (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         TEXT NOT NULL REFERENCES evaluation_run(run_id),
    submission_id  UUID NOT NULL REFERENCES submission(submission_id),
    result_version INTEGER NOT NULL,
    model          TEXT NOT NULL,
    curve          TEXT NOT NULL,
    step           INTEGER NOT NULL,
    value          DOUBLE PRECISION NOT NULL,
    UNIQUE (run_id, model, curve, step, result_version)
);
CREATE INDEX training_loss_point_lookup_idx ON training_loss_point (run_id, model);

-- ---------------------------------------------------------- batch runner

CREATE TABLE batch_variant_score (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         TEXT NOT NULL REFERENCES evaluation_run(run_id),
    submission_id  UUID NOT NULL REFERENCES submission(submission_id),
    image_id       TEXT NOT NULL,
    result_version INTEGER NOT NULL,
    variant        TEXT NOT NULL,             -- 7 ablation variants, app-enforced
    ssim           DOUBLE PRECISION NOT NULL,
    psnr           DOUBLE PRECISION,
    latency_ms     DOUBLE PRECISION,
    UNIQUE (run_id, image_id, variant, result_version)
);
CREATE INDEX batch_variant_score_lookup_idx ON batch_variant_score (run_id, image_id);

-- ------------------------------------------------------------- bootstrap

CREATE TABLE bootstrap_comparison_result (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id              TEXT NOT NULL REFERENCES evaluation_run(run_id),
    submission_id       UUID NOT NULL REFERENCES submission(submission_id),
    result_version      INTEGER NOT NULL,
    comparison_key      TEXT NOT NULL,
    metric              TEXT NOT NULL,
    n_images            INTEGER NOT NULL,
    n_comparisons       INTEGER NOT NULL,
    corrected_alpha     DOUBLE PRECISION NOT NULL,
    mean_delta          DOUBLE PRECISION NOT NULL,
    ci_lower            DOUBLE PRECISION NOT NULL,
    ci_upper            DOUBLE PRECISION NOT NULL,
    ci_width            DOUBLE PRECISION NOT NULL,
    significance_status TEXT NOT NULL,        -- significant|directional
    resamples           INTEGER NOT NULL DEFAULT 10000,
    computed_at         TIMESTAMPTZ NOT NULL,
    UNIQUE (run_id, comparison_key, metric, result_version)
);
CREATE INDEX bootstrap_comparison_result_run_idx ON bootstrap_comparison_result (run_id);

-- ------------------------------------------------- held-out test manifest

