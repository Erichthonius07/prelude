    sha256           VARCHAR(64) NOT NULL UNIQUE,
    source           TEXT NOT NULL,           -- sidd|team_capture
    manifest_version INTEGER NOT NULL DEFAULT 1,
    added_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);